#!/usr/bin/env node
/* eslint-disable @typescript-eslint/no-require-imports */
/**
 * Custom Prisma generator that emits a typed sensitivity-classification map
 * from /// @sensitivity:<tier> comments on each scalar/enum field.
 *
 * Wired into prisma/schema.prisma as `generator security`. Runs as part of
 * `prisma generate`. Throws on any unannotated or unknown-tier field.
 *
 * Written in plain JS (not TS) so the generator runs without a ts-node
 * bootstrap — Prisma's generator launcher doesn't shell-parse args, which
 * makes passing --compiler-options into ts-node unreliable.
 */
const { generatorHandler } = require('@prisma/generator-helper');
const fs = require('node:fs/promises');
const path = require('node:path');

const VALID_TIERS = ['public', 'member', 'pii', 'personal', 'internal', 'hardship', 'secret'];

function parseTier(documentation) {
    if (!documentation) return null;
    const match = /@sensitivity:(\w+)/.exec(documentation);
    if (!match) return null;
    return VALID_TIERS.includes(match[1]) ? match[1] : null;
}

generatorHandler({
    onManifest: () => ({
        defaultOutput: '../src/security/generated/classifications.ts',
        prettyName: 'Security Classifications',
    }),
    onGenerate: async (options) => {
        const errors = [];
        const lines = [
            '// GENERATED by scripts/security-generator.js — do not edit by hand.',
            '// Re-run `prisma generate` after editing /// @sensitivity comments.',
            '',
            'export const classifications = {',
        ];

        for (const model of options.dmmf.datamodel.models) {
            lines.push(`    ${model.name}: {`);
            for (const field of model.fields) {
                if (field.kind !== 'scalar' && field.kind !== 'enum') continue;

                const documentation = field.documentation;
                if (!documentation || !/@sensitivity:/.test(documentation)) {
                    errors.push(`${model.name}.${field.name}: missing /// @sensitivity:<tier>`);
                    continue;
                }

                const tier = parseTier(documentation);
                if (!tier) {
                    const rawTag = /@sensitivity:(\S+)/.exec(documentation)?.[1] ?? '<unknown>';
                    errors.push(`${model.name}.${field.name}: unknown tier '${rawTag}' (must be one of ${VALID_TIERS.join(', ')})`);
                    continue;
                }

                lines.push(`        ${field.name}: '${tier}',`);
            }
            lines.push('    },');
        }

        lines.push('} as const;');
        lines.push('');
        lines.push('export const relations = {');
        for (const model of options.dmmf.datamodel.models) {
            lines.push(`    ${model.name}: {`);
            for (const field of model.fields) {
                if (field.kind !== 'object') continue;
                lines.push(`        ${field.name}: { model: '${field.type}', isList: ${field.isList} },`);
            }
            lines.push('    },');
        }
        lines.push('} as const;');
        lines.push('');
        lines.push('export type Models = keyof typeof classifications;');
        lines.push('export type FieldsOf<M extends Models> = keyof (typeof classifications)[M];');
        lines.push('export type TierOf<M extends Models, F extends FieldsOf<M>> = (typeof classifications)[M][F];');
        lines.push('');

        if (errors.length) {
            throw new Error(
                'Sensitivity annotations missing or invalid:\n  ' + errors.join('\n  '),
            );
        }

        const outputPath = options.generator.output?.value;
        if (!outputPath) throw new Error('No output path configured for security generator');

        await fs.mkdir(path.dirname(outputPath), { recursive: true });
        await fs.writeFile(outputPath, lines.join('\n'));
    },
});
